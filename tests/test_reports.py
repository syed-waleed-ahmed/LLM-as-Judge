WHEN = datetime(2026, 11, 10, 12, 0, tzinfo=timezone.utc)


def _judge() -> Judge:
    return Judge(MockProvider(), Settings(_env_file=None, provider="mock"))


def _pairs(n: int = 4) -> list[PairwiseRecord]:
    return [
        PairwiseRecord(
            id=f"r{i}",
            task_description=f"Explain topic {i}",
            output_a=f"A thorough, accurate explanation of topic {i} with an example.",
            output_b="Short.",
            model_a="alpha",
            model_b="beta",
        )
        for i in range(n)
    ]


def _record(store, *, name, instructions=None, judge=None, records=None):
    judge = judge or _judge()
    report = DatasetRunner(judge, ["Helpfulness"], instructions=instructions).run(
        records or _pairs()
    )
    return record_dataset_run(store, report, judge, experiment="exp", name=name)


def _json_block(markdown: str) -> dict:
    match = re.search(r"```json\n(.*?)\n```", markdown, re.S)
    assert match
    return json.loads(match.group(1))


def test_pairwise_report_restates_the_stored_run():
    store = ExperimentStore(":memory:")
    run = _record(store, name="baseline")
    text = run_report(store, run.id, generated_at=WHEN)
    stored = store.require_run(run.id)

    assert text.startswith("# Evaluation report: baseline\n")
    assert "Generated by LLM-as-Judge" in text and "2026-11-10 12:00 UTC" in text
    assert f"| Run id | `{run.id}` |" in text
    assert "| Judge | mock · mock-heuristic-v1 |" in text
    assert "**Mock judge.**" in text and "ignores judge instructions" in text
    assert "| Helpfulness | 1-10 | 1 |" in text  # weight shown as 1, not 1.000
    summary = stored.summary
    wins = summary["wins_a"]
    assert f"| Wins | {wins} ({wins / summary['succeeded']:.0%})" in text
    assert "### Per model" in text and "| alpha | 4 |" in text
    assert "## Failed rows" not in text  # nothing failed
    assert _json_block(text)["prompt_version"] == stored.prompt_version


def test_graded_report_and_failed_rows():
    def reply(messages):
        if "explode" in messages[1]["content"]:
            raise ProviderError("upstream exploded")
        return make_pointwise_payload(("Correctness", 7), ("Completeness", 6), missing=[])

    judge = Judge(FnProvider(reply), Settings(_env_file=None, groq_api_key="k", max_retries=0))
    records = [
        ReferenceRecord(id="ok", task_description="t", output="out", reference="ref"),
        ReferenceRecord(id="bad", task_description="t", output="explode", reference="ref"),
    ]
    store = ExperimentStore(":memory:")
    report = DatasetRunner(judge).run(records)
    run = record_dataset_run(store, report, judge, experiment="exp", name="graded")
    text = run_report(store, run.id)
    assert "| Mean overall score (0-1) |" in text
    assert "| Mean token F1 vs reference |" in text
    assert "## Failed rows" in text and "| bad | upstream exploded |" in text
    assert "**Mock judge.**" not in text


def test_comparison_section_and_instruction_caveat():
    store = ExperimentStore(":memory:")
    base = _record(store, name="base")
    guided = _record(store, name="guided", instructions="Be strict about examples.")
    text = run_report(store, guided.id, baseline_id=base.id)
    assert "## Comparison with the baseline" in text
    assert f"baseline `{base.id}`" in text
    assert "| Matched rows | 4 |" in text
    assert "> Be strict about examples." in text  # the run's own instructions
    assert "differ in judge instructions" in text  # surfaced as a caveat


def test_report_accepts_prefixes_and_rejects_unknown_runs():
    store = ExperimentStore(":memory:")
    run = _record(store, name="only")
    assert "# Evaluation report: only" in run_report(store, run.id[:12])
    with pytest.raises(ExperimentError):
        run_report(store, "no-such-run")


@pytest.mark.parametrize(
    ("value", "expected"),
    [(None, "-"), ("", "-"), (0.5, "0.500"), ("a|b\nc", "a\\|b c"), (3, "3")],
)
def test_table_cells_are_escaped(value, expected):
    assert _cell(value) == expected


def test_cli_writes_a_report(tmp_path, capsys):
    db = tmp_path / "exp.db"
    store = ExperimentStore(db)
    run = _record(store, name="cli")
    store.close()
    out = tmp_path / "reports" / "run.md"
    assert main(["experiments", "--db", str(db), "report", run.id, "--output", str(out)]) == 0
    assert out.read_text(encoding="utf-8").startswith("# Evaluation report: cli")
    capsys.readouterr()
    assert main(["experiments", "--db", str(db), "report", run.id]) == 0
    assert "## Reproducibility" in capsys.readouterr().out


def test_api_experiment_detail_and_run_report():
    pytest.importorskip("fastapi")
    from fastapi.testclient import TestClient

    from llm_judge.api import create_app

    store = ExperimentStore(":memory:")
    first = _record(store, name="first")
    second = _record(store, name="second")
    settings = Settings(
        _env_file=None, provider="mock", db_path=":memory:", api_rate_limit_per_minute=0
    )
    client = TestClient(create_app(settings, store=store), raise_server_exceptions=False)

    detail = client.get("/api/v1/experiments/exp", params={"limit": 1})
    assert detail.status_code == 200, detail.text
    body = detail.json()
    assert body["experiment"]["name"] == "exp" and body["total_runs"] == 2
    assert [r["id"] for r in body["runs"]] == [second.id]  # newest first, paginated
    assert client.get("/api/v1/experiments/missing").status_code == 404

    report = client.get(f"/api/v1/runs/{second.id}/report", params={"baseline": first.id})
    assert report.status_code == 200
    assert report.headers["content-type"].startswith("text/markdown")
    assert "## Comparison with the baseline" in report.text
    assert client.get("/api/v1/runs/nope/report").status_code == 404
